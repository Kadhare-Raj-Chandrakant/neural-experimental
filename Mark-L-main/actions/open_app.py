def _normalize(raw: str) -> str:
    key = raw.lower().strip()

    if key in _APP_ALIASES:
        return _APP_ALIASES[key].get(_SYSTEM, raw)

    for alias_key, os_map in _APP_ALIASES.items():
        if alias_key in key or key in alias_key:
            return os_map.get(_SYSTEM, raw)

    return raw  

def _launch_windows(app_name: str) -> bool:
    app_lower = app_name.lower().strip()

    # Specialized Windows 11 Apps (like Paint, Notepad)
    if app_lower in ("paint", "mspaint", "mspaint.exe", "notepad", "notepad.exe"):
        try:
            exe = "notepad.exe" if "notepad" in app_lower else "mspaint.exe"
            subprocess.Popen(exe, shell=True)
            time.sleep(1.0)
            from actions.coordinate_grounding import WindowIdentifier
            if WindowIdentifier.bring_to_front("notepad" if "notepad" in app_lower else "paint"):
                time.sleep(0.5)
                return True
        except Exception as e:
            print(f"[open_app] {app_lower} direct launch note: {e}")

    if shutil.which(app_name) or shutil.which(app_name.split(".")[0]):
        try:
            subprocess.Popen(
                app_name,
                shell=True,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            time.sleep(1.5)
            return True
        except Exception as e:
            print(f"[open_app] subprocess failed: {e}")

    if ":" in app_name:
        try:
            subprocess.Popen(f"start {app_name}", shell=True)
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        import pyautogui
        pyautogui.PAUSE = 0.1
        pyautogui.press("win")
        time.sleep(0.7)
        pyautogui.write(app_name, interval=0.05)
        time.sleep(0.9)
        pyautogui.press("enter")
        time.sleep(2.5)
        return True
    except Exception as e:
        print(f"[open_app] Start Menu search failed: {e}")

    return False


def _launch_macos(app_name: str) -> bool:

    try:
        result = subprocess.run(
            ["open", "-a", app_name],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    try:
        result = subprocess.run(
            ["open", "-a", f"{app_name}.app"],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    binary = shutil.which(app_name) or shutil.which(app_name.lower())
    if binary:
        try:
            subprocess.Popen(
                [binary],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        import pyautogui
        pyautogui.hotkey("command", "space")
        time.sleep(0.6)
        pyautogui.write(app_name, interval=0.05)
        time.sleep(0.8)
        pyautogui.press("enter")
        time.sleep(1.5)
        return True
    except Exception as e:
        print(f"[open_app] Spotlight failed: {e}")

    return False


_LINUX_TERMINAL_FALLBACKS = [
    "x-terminal-emulator", "gnome-terminal", "konsole", "xfce4-terminal",
    "xterm", "lxterminal", "mate-terminal", "tilix", "alacritty", "kitty",
]

def _launch_linux(app_name: str) -> bool:

    # terminal emulators: try common ones in order
    if app_name in ("x-terminal-emulator", "gnome-terminal", "terminal"):
        for term in _LINUX_TERMINAL_FALLBACKS:
            if shutil.which(term):
                try:
                    subprocess.Popen([term], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    time.sleep(1.0)
                    return True
                except Exception:
                    continue

    binary = (
        shutil.which(app_name) or
        shutil.which(app_name.lower()) or
        shutil.which(app_name.lower().replace(" ", "-")) or
        shutil.which(app_name.lower().replace(" ", "_"))
    )
    if binary:
        try:
            subprocess.Popen(
                [binary],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        subprocess.run(
            ["xdg-open", app_name],
            capture_output=True, timeout=5
        )
        return True
    except Exception:
        pass

    for desktop_name in [
        app_name.lower(),
        app_name.lower().replace(" ", "-"),
        app_name.lower().replace(" ", ""),
    ]:
        try:
            result = subprocess.run(
                ["gtk-launch", desktop_name],
                capture_output=True, timeout=5
            )
            if result.returncode == 0:
                return True
        except Exception:
            pass

    return False


def _launch_in_terminal_windows(command: str, terminal_type: str = "terminal") -> bool:
    command = command.strip()
    if not command:
        return False
    term_lower = terminal_type.lower()
    try:
        if "powershell" in term_lower:
            subprocess.Popen(f'start powershell.exe -NoExit -Command "{command}"', shell=True)
            return True

        wt = shutil.which("wt.exe") or shutil.which("wt")
        if wt:
            subprocess.Popen(f'wt.exe cmd /k "{command}"', shell=True)
            return True

        subprocess.Popen(f'start cmd /k "{command}"', shell=True)
        return True
    except Exception as e:
        print(f"[open_app] terminal command execution failed: {e}")
        return False


def _launch_in_terminal_macos(command: str, terminal_type: str = "terminal") -> bool:
    command = command.strip().replace('"', '\\"')
    try:
        script = f'tell application "Terminal" to do script "{command}"\\ntell application "Terminal" to activate'
        subprocess.run(["osascript", "-e", script], timeout=5)
        return True
    except Exception as e:
        print(f"[open_app] macos terminal launch failed: {e}")
        return False


def _launch_in_terminal_linux(command: str, terminal_type: str = "terminal") -> bool:
    command = command.strip().replace("'", "\\'")
    try:
        for term in _LINUX_TERMINAL_FALLBACKS:
            if shutil.which(term):
                subprocess.Popen([term, "-e", f"bash -c '{command}; exec bash'"])
                return True
        return False
    except Exception as e:
        print(f"[open_app] linux terminal launch failed: {e}")
        return False


_TERMINAL_LAUNCHERS = {
    "Windows": _launch_in_terminal_windows,
    "Darwin":  _launch_in_terminal_macos,
    "Linux":   _launch_in_terminal_linux,
}

_OS_LAUNCHERS = {
    "Windows": _launch_windows,
    "Darwin":  _launch_macos,
    "Linux":   _launch_linux,
}

def open_app(
    parameters=None,
    response=None,
    player=None,
    session_memory=None,
) -> str:
    params = parameters or {}
    app_name = params.get("app_name", "").strip()
    command = params.get("command", "").strip()

    if not app_name and not command:
        return "No application name or command provided."

    # Triage via DecisionEngine (powered by Laya)
    try:
        from actions.decision_engine import DecisionEngine
        triage = DecisionEngine.triage_app_launch(app_name, command)
        if triage.get("is_terminal_command"):
            target_term = triage.get("terminal_type", "terminal")
            target_cmd = triage.get("command", "")
            print(f"[open_app] Terminal execution triage: '{target_cmd}' via '{target_term}' ({_SYSTEM})")
            if player:
                player.write_log(f"[open_app] Terminal: {target_cmd}")
            term_launcher = _TERMINAL_LAUNCHERS.get(_SYSTEM)
            if term_launcher and term_launcher(target_cmd, target_term):
                return f"Opened terminal and executed: {target_cmd}"
            else:
                return f"Attempted to run '{target_cmd}' in terminal, but the terminal launcher encountered an error."
    except Exception as e:
        print(f"[open_app] Triage fallback note: {e}")

    launcher = _OS_LAUNCHERS.get(_SYSTEM)
    if launcher is None:
        return f"Unsupported operating system: {_SYSTEM}"

    normalized = _normalize(app_name)
    print(f"[open_app] Launching: '{app_name}' → '{normalized}' ({_SYSTEM})")

    if player:
        player.write_log(f"[open_app] {app_name}")

    try:
        launched = False
        if launcher(normalized):
            launched = True
        elif normalized.lower() != app_name.lower() and launcher(app_name):
            launched = True

        if launched:
            # Engage visual observation and wait for target window to focus
            try:
                from actions.coordinate_grounding import WindowIdentifier
                from actions.vision_pipeline import VisionSessionManager
                VisionSessionManager.get_instance().start_observation()
                WindowIdentifier.wait_for_target_window(app_name, timeout=2.5)
            except Exception:
                pass
            return f"Opened {app_name} and verified active window."

        return (
            f"Could not confirm that {app_name} launched. "
            f"It may still be loading, or it might not be installed."
        )
    except Exception as e:
        print(f"[open_app] Error: {e}")
        return f"Failed to open {app_name}: {e}"